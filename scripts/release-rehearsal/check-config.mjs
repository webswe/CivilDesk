import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const workflow = fs.readFileSync(path.join(root, '.github/workflows/tester-installer-rehearsal.yml'), 'utf8');
const config = JSON.parse(fs.readFileSync(path.join(root, 'src-tauri/tauri.conf.json'), 'utf8'));
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
const lock = JSON.parse(fs.readFileSync(path.join(root, 'package-lock.json'), 'utf8'));
const cargo = fs.readFileSync(path.join(root, 'src-tauri/Cargo.toml'), 'utf8');
const cargoLock = fs.readFileSync(path.join(root, 'src-tauri/Cargo.lock'), 'utf8');
assert.equal(config.version, '0.1.1');
assert.equal(pkg.version, '0.1.1');
assert.equal(lock.version, '0.1.1');
assert.equal(lock.packages[''].version, '0.1.1');
assert.match(cargo, /\[package\][\s\S]*?version = "0\.1\.1"/);
assert.match(cargoLock, /name = "civildesk"\s+version = "0\.1\.1"/);
assert.equal(config.identifier, 'com.webswe.civildesk');
assert.equal(config.bundle.windows.nsis.installMode, 'currentUser');
assert.equal(config.bundle.windows.webviewInstallMode.type, 'offlineInstaller');
assert.match(workflow, /workflow_dispatch:/);
assert.doesNotMatch(workflow, /^\s*(push|pull_request|schedule|workflow_run|release):/m);
assert.match(workflow, /runs-on: windows-2022/);
assert.doesNotMatch(workflow, /runs-on:\s*self-hosted|actions\/upload-artifact|contents: write|secrets\.|tauri-action|createRelease|gh release/i);
assert.match(workflow, /APPROVED_CANDIDATE_SHA: UNSET/);
assert.match(workflow, /7d293bbc61dce674d796220e3241571a9f15aa6b/);
assert.match(workflow, /RUNNER_ENVIRONMENT -cne 'github-hosted'/);
assert.match(workflow, /persist-credentials: false/g);
console.log('Release rehearsal configuration is manual, pinned, synthetic, and fail-closed.');
